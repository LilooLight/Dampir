function renderReference() {
  const q = ($('#refSearch').value || '').trim().toLowerCase();
  const cat = $('#refCat').value || 'all';
  const cats = cat === 'all' ? CAT_ORDER : [cat];
  let html = '',
    found = 0;
  for (const key of cats) {
    const sec = gameData[key];
    if (key === 'weapons') {
      const items = sec.filter(w => (w.n + ' ' + w.d + ' ' + w.st + ' ' + w.price).toLowerCase().includes(q));
      if (q && !items.length) continue;
      found += items.length;
      html += '<section class="cat">' + sectionHead(key, items.length) + weaponsTableHTML(items, q) + '</section>';
    } else if (key === 'armor') {
      const groups = sec.map(g => ({ name: g.name, rows: g.rows.filter(r => (r.n + ' ' + r.slot + ' ' + r.pen).toLowerCase().includes(q)) }))
        .filter(g => !q || g.rows.length);
      const count = groups.reduce((s, g) => s + g.rows.length, 0);
      if (q && !count) continue;
      found += count;
      html += '<section class="cat">' + sectionHead(key, count) + armorTablesHTML(groups, q) + '</section>';
    } else {
      const items = sec.filter(it => {
        const s = it.n + ' ' + it.s + ' ' + it.d + (it.sp ? it.sp.map(x => x.n).join(' ') : '') + (it.lv ? it.lv.map(x => x.n).join(' ') : '');
        return s.toLowerCase().includes(q);
      });
      if (q && !items.length) continue;
      found += items.length;
      html += '<section class="cat">' + sectionHead(key, items.length) + '<div class="cards">' + items.map(it => cardHTML(it, key, q)).join('') + '</div></section>';
    }
  }
  if (!found && q) {
    html = '<div class="empty"><span class="diam">' + icon('diamond') + '</span>По запросу «' + esc(q) + '» ничего не найдено.</div>';
  }
  $('#refList').innerHTML = html;
}

function sectionHead(key, count) {
  const m = CAT_META[key];
  return `<div class="cat-head"><span class="diam">${icon('diamond')}</span><h2 class="cat-title">${esc(m.title)}</h2><span class="cat-count">${count} ${pluralize(count,['позиция','позиции','позиций'])}</span></div>`;
}

function cardHTML(it, key, q) {
  let meta = '';
  if (it.sp) meta = it.sp.length + ' ' + pluralize(it.sp.length, ['специализация', 'специализации', 'специализаций']);
  if (it.lv) meta = 'уровни I–IV · есть расплата';
  if (key === 'traits') {
    const good = it.k === 'Достоинство';
    meta = `<span class="${good?'tag-good':'tag-bad'}">${esc(it.k)}${good?' · '+esc(it.c)+' опыта':' · даёт '+esc(it.c)+' опыта'}</span>`;
  }
  return `<article class="card" data-cat="${key}" data-item="${it.id}"><h3 class="card-name"><span class="diam">${icon('diamond')}</span>${hl(it.n,q)}</h3><p class="card-short">${hl(it.s,q)}</p>${meta?'<p class="card-meta">'+meta+'</p>':''}</article>`;
}

function hl(text, q) {
  const safe = esc(text);
  if (!q) return safe;
  const re = new RegExp('(' + esc(q).replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + ')', 'gi');
  return safe.replace(re, '<mark>$1</mark>');
}

function weaponsTableHTML(items, q) {
  return `<div class="table-scroll"><table><thead><tr><th>Название</th><th class="num">Урон</th><th>Скрытность</th><th class="num">МС наст.</th><th class="num">МС обор.</th><th class="num">ББ</th><th>Стиль</th><th class="num">Цена</th></tr></thead><tbody>${
    items.map(w => `<tr data-cat="weapons" data-item="${w.id}"><td class="rowname">${hl(w.n,q)}</td><td class="num">${w.dmg}</td><td>${w.hid}</td><td class="num">${w.m1}</td><td class="num">${w.m2}</td><td class="num">${w.ap}</td><td>${w.st}</td><td class="num">${w.price}</td></tr>`).join('')
  }</tbody></table></div><p class="tnote">МС — модификатор костей боевого стиля. ББ — бронебойность.</p>`;
}

function armorTablesHTML(groups, q) {
  return groups.map(g => `<div class="armor-group"><h3>${esc(g.name)}</h3><div class="table-scroll"><table><thead><tr><th>Часть тела</th><th>Название</th><th class="num">Броня</th><th class="num">Треб. Силы</th><th>Штрафы</th><th class="num">Вес</th><th class="num">Цена</th></tr></thead><tbody>${
    g.rows.map(r => `<tr data-cat="armor" data-item="${r.id}"><td>${r.slot}</td><td class="rowname">${hl(r.n,q)}</td><td class="num">${r.a}</td><td class="num">${r.str}</td><td>${r.pen}</td><td class="num">${r.w}</td><td class="num">${r.price}</td></tr>`).join('')
  }</tbody></table></div></div>`).join('') + '<p class="tnote">Требование к Силе — минимальное значение качества.</p>';
}

