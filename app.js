function renderLog() {
  const sel = $('#logCharFilter');
  const current = state.characters.some(c => c.id === logCharFilter) ? logCharFilter : 'all';
  sel.innerHTML = `<option value="all">Все скитальцы</option>` +
    state.characters.map(c => `<option value="${c.id}"${c.id===current?' selected':''}>${esc(c.name)}</option>`).join('');
  logCharFilter = current;
  $('#logCount').textContent = state.log.length ?
    state.log.length + ' ' + pluralize(state.log.length, ['запись', 'записи', 'записей']) :
    '';
  let rows = state.log.filter(l => logCharFilter === 'all' || l.charId === logCharFilter);
  rows = rows.slice().sort((a, b) => {
    if (logSort.key === 'ts') return (a.ts - b.ts) * logSort.dir;
    return a.charName.localeCompare(b.charName, 'ru') * logSort.dir;
  });
  const arrow = k => logSort.key === k ? `<span class="sort-arrow">${logSort.dir===1?'▴':'▾'}</span>` : '';
  if (!rows.length) {
    $('#logWrap').innerHTML = `<div class="empty"><span class="diam">${icon('diamond')}</span>Летопись пока чиста.</div>`;
    return;
  }
  $('#logWrap').innerHTML = `<div class="table-scroll"><table><thead><tr>
    <th class="sortable" data-sort="ts">Дата${arrow('ts')}</th>
    <th class="sortable" data-sort="name">Персонаж${arrow('name')}</th>
    <th>Тип</th><th class="num">Кол-во</th><th>Причина</th>
    </tr></thead><tbody>
    ${rows.map(l => `
      <tr><td style="white-space:nowrap">${fmtDate(l.ts)}</td>
      <td>${esc(l.charName)}</td>
      <td><span class="sign ${l.type==='+'?'plus':'minus'}">${l.type}</span>${l.type==='+'?'получение':'трата'}</td>
      <td class="num">${l.amount}</td>
      <td>${esc(l.reason)}</td></tr>
    `).join('')}
    </tbody></table></div>`;
}

