function openXpModal(c, mode) {
  const isAdd = mode === 'add';
  openModal((isAdd ? 'Добавить опыт · ' : 'Потратить опыт · ') + esc(c.name),
    `<form id="xpForm">
      <div class="field"><label>Количество</label><input type="number" id="xpAmount" min="1" step="1" value="1"></div>
      <div class="field"><label>Причина</label><input type="text" id="xpReason" maxlength="120" placeholder="${isAdd?'подвиг, найденный клад, урок мастера…':'обучение, снаряжение, услуга…'}"></div>
      <p class="warn hidden" id="xpWarn">Внимание: опыт уйдёт в минус.</p>
      <div class="modal-actions">
        <button type="button" class="btn" id="xpCancel">Отмена</button>
        <button type="submit" class="btn ${isAdd?'gold':'blood'}">${isAdd?'Записать прибавку':'Записать трату'}</button>
      </div>
    </form>`);
  const amountEl = $('#xpAmount');
  const warnEl = $('#xpWarn');
  amountEl.addEventListener('input', function() {
    const v = parseInt(this.value, 10) || 0;
    warnEl.classList.toggle('hidden', isAdd || (c.xp - v) >= 0);
  });
  $('#xpCancel').addEventListener('click', closeModal);
  $('#xpForm').addEventListener('submit', function(e) {
    e.preventDefault();
    const amount = parseInt(amountEl.value, 10);
    if (!amount || amount < 1) { toast('Укажите количество больше нуля', false); return; }
    const reason = $('#xpReason').value.trim() || 'Без причины';
    c.xp += isAdd ? amount : -amount;
    state.log.push({ id: uid(), ts: Date.now(), charId: c.id, charName: c.name,
      type: isAdd ? '+' : '−', amount, reason });
    saveState();
    closeModal();
    renderTracker();
    toast(`${isAdd?'+':'−'}${amount} · ${c.name} — «${reason}»`);
  });
  amountEl.focus();
  amountEl.select();
}

