function openRollModal({ char, skillName, pool, hasSpec }) {
  const html = `
    <p class="modal-kicker">Проверка: ${esc(skillName)}</p>
    <div class="field"><label>Пул (количество костей d10)</label><input type="number" id="rollPool" value="${pool}" min="0" max="30"></div>
    <div class="field"><label>Сложность (успех при ≥)</label><input type="number" id="rollDiff" value="6" min="2" max="10"></div>
    <div class="field"><label><input type="checkbox" id="rollSpec" ${hasSpec?'checked':''} ${!hasSpec?'disabled':''}> Специализация (десятки дают +1 успех)</label></div>
    <div class="field"><label><input type="checkbox" id="rollOver"> Сверхусилие (+1 стресс, можно перебросить до 3 кубов после броска)</label></div>
    <div id="rollResult" style="margin-top:1rem;padding:.6rem;background:var(--bg-deep);border:1px solid var(--line);min-height:2rem;"></div>
    <div class="modal-actions">
      <button class="btn" id="rollCancel">Отмена</button>
      <button class="btn gold" id="rollGo">Бросить</button>
    </div>
  `;
  openModal('🎲 Бросок', html);
  const poolEl = $('#rollPool'),
    diffEl = $('#rollDiff'),
    specEl = $('#rollSpec'),
    overEl = $('#rollOver'),
    resultEl = $('#rollResult');

  function doRoll() {
    const dice = parseInt(poolEl.value) || 0;
    const diff = parseInt(diffEl.value) || 6;
    const spec = specEl.checked;
    const over = overEl.checked;
    if (dice <= 0) { resultEl.innerHTML = '<span style="color:var(--blood-bright);">Пул должен быть больше нуля</span>'; return; }
    if (over) {
      const maxStress = (char.virtues.composure || 1) + (char.virtues.courage || 1) + 2;
      if (char.stress >= maxStress) {
        resultEl.innerHTML = '<span style="color:var(--blood-bright);">⚠️ Стресс переполнен! Сначала снизьте стресс.</span>';
        return;
      }
      char.stress += 1;
      saveState();
      renderSheet();
    }
    // Генерация d10
    const results = [];
    for (let i = 0; i < dice; i++) results.push(Math.floor(Math.random() * 10) + 1);
    let successes = 0,
      ones = 0,
      tens = 0;
    results.forEach(v => {
      if (v >= diff) successes++;
      if (v === 1) ones++;
      if (v === 10) tens++;
    });
    if (spec && tens) successes += tens; // специализация: каждая десятка даёт +1 доп. успех
    let critFail = false;
    if (ones > 0 && successes === 0) critFail = true;
    const finalSuccess = Math.max(0, successes - ones);

    resultEl.innerHTML = `
      <div style="display:flex;flex-wrap:wrap;gap:.3rem;margin-bottom:.5rem;">
        ${results.map((v,i) => `<span style="display:inline-block;padding:.1rem .6rem;background:${v>=diff?'var(--gold)':'var(--bg-deep)'};border:1px solid var(--line);color:${v>=diff?'#1a1a1a':'var(--ink-dim)'};font-weight:${v>=diff?'700':'400'};">${v}</span>`).join('')}
      </div>
      <div>Успехов (>=${diff}): ${successes} ${spec?'(с учётом критов)':''}</div>
      <div>Единиц: ${ones} (отменяют успехи)</div>
      <div>Итог: ${finalSuccess} успех${pluralize(finalSuccess,['','а','ов'])} ${critFail?'<span style="color:var(--blood-bright);">⚠️ КРИТИЧЕСКИЙ ПРОВАЛ!</span>':''}</div>
    `;

    // Если сверхусилие, предлагаем перебросить
    if (over && !critFail) {
      resultEl.innerHTML += '<button class="btn" id="rerollBtn" style="margin-top:.5rem;">Перебросить до 3 кубов (сверхусилие)</button>';
      $('#rerollBtn').addEventListener('click', function() {
        // Перебросить первые 3 куба
        const toReroll = results.slice(0, 3);
        const newResults = toReroll.map(() => Math.floor(Math.random() * 10) + 1);
        results.splice(0, 3, ...newResults);
        successes = 0;
        ones = 0;
        tens = 0;
        results.forEach(v => {
          if (v >= diff) successes++;
          if (v === 1) ones++;
          if (v === 10) tens++;
        });
        if (spec && tens) successes += tens;
        critFail = false;
        if (ones > 0 && successes === 0) critFail = true;
        const finalSuccess2 = Math.max(0, successes - ones);
        resultEl.innerHTML = `
          <div style="display:flex;flex-wrap:wrap;gap:.3rem;margin-bottom:.5rem;">
            ${results.map((v,i) => `<span style="display:inline-block;padding:.1rem .6rem;background:${v>=diff?'var(--gold)':'var(--bg-deep)'};border:1px solid var(--line);color:${v>=diff?'#1a1a1a':'var(--ink-dim)'};font-weight:${v>=diff?'700':'400'};">${v}</span>`).join('')}
          </div>
          <div>Успехов (>=${diff}): ${successes} ${spec?'(с учётом критов)':''}</div>
          <div>Единиц: ${ones} (отменяют успехи)</div>
          <div>Итог: ${finalSuccess2} успех${pluralize(finalSuccess2,['','а','ов'])} ${critFail?'<span style="color:var(--blood-bright);">⚠️ КРИТИЧЕСКИЙ ПРОВАЛ!</span>':''}</div>
        `;
        toast('Переброс выполнен');
      });
    }
  }

  $('#rollGo').addEventListener('click', doRoll);
  $('#rollCancel').addEventListener('click', closeModal);
  [poolEl, diffEl].forEach(el => el.addEventListener('keydown', e => { if (e.key === 'Enter') doRoll(); }));
  doRoll(); // автоматический первый бросок при открытии
}

