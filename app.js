function openItemModal(key, id) {
  const meta = CAT_META[key];
  let body = '',
    title = '';
  if (key === 'weapons') {
    const w = gameData.weapons.find(x => x.id === id);
    if (!w) return;
    title = w.n;
    body = `<p class="modal-kicker">${meta.kicker}</p><dl class="props">${['dmg','hid','m1','m2','ap','st','price'].map(f => `<div><dt>${f==='dmg'?'Урон':f==='hid'?'Скрытность':f==='m1'?'МС наст.':f==='m2'?'МС обор.':f==='ap'?'ББ':f==='st'?'Стиль':'Цена'}</dt><dd>${esc(w[f])}</dd></div>`).join('')}</dl><p class="d-desc d-drop">${esc(w.d)}</p>`;
  } else if (key === 'armor') {
    let row = null,
      group = null;
    for (const g of gameData.armor) { const r = g.rows.find(x => x.id === id); if (r) { row = r;
        group = g; break; } }
    if (!row) return;
    title = row.n;
    body = `<p class="modal-kicker">${meta.kicker} · ${esc(group.name)}</p><dl class="props">${['slot','a','str','pen','w','price'].map(f => `<div><dt>${f==='slot'?'Часть тела':f==='a'?'Броня':f==='str'?'Треб. Силы':f==='pen'?'Штрафы':f==='w'?'Вес':'Цена'}</dt><dd>${esc(row[f])}</dd></div>`).join('')}</dl><div class="d-block"><span class="lbl">Игромеханика</span><p>Броня вычитается из урона по прикрытой части тела.</p></div>`;
  } else {
    const it = gameData[key].find(x => x.id === id);
    if (!it) return;
    title = it.n;
    body = `<p class="modal-kicker">${meta.kicker}</p><p class="d-desc d-drop">${esc(it.d)}</p>`;
    if (it.m) body += `<div class="d-block"><span class="lbl">Игромеханика</span><p>${esc(it.m)}</p></div>`;
    if (it.sp) body += `<div class="d-block"><span class="lbl">Специализации</span><ul class="specs">${it.sp.map(s=>`<li><b>${esc(s.n)}</b><span>— ${esc(s.d)}</span></li>`).join('')}</ul></div>`;
    if (it.pr) body += `<div class="d-block bloodline"><span class="lbl">Расплата</span><p>${esc(it.pr)}</p></div>`;
    if (it.lv) body += `<div class="d-block bloodline"><span class="lbl">Уровни и проявления</span><div>${it.lv.map(l=>`<div class="lvl"><span class="lvl-num"><span>${l.lv}</span></span><div><b>${esc(l.n)}.</b><p>${esc(l.d)}</p></div></div>`).join('')}</div></div>`;
    if (key === 'traits') {
      const good = it.k === 'Достоинство';
      body += `<div class="d-block"><span class="lbl">${good?'Стоимость':'Даёт опыта'}</span><p>${good ? esc(it.c)+' опыта' : esc(it.c)+' опыта'}</p></div>`;
    }
  }
  openModal(esc(title), body);
}

