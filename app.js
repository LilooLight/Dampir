const STORE_KEY = 'skitalets_full_v3';
let state = { characters: [], activeCharId: null, log: [] };
let logSort = { key: 'ts', dir: -1 };
let logCharFilter = 'all';

function loadState() {
  try {
    const raw = localStorage.getItem(STORE_KEY);
    if (!raw) return;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed.characters) && Array.isArray(parsed.log)) {
      state = parsed;
      if (!state.activeCharId && state.characters.length) state.activeCharId = state.characters[0].id;
    }
  } catch (e) {}
}

function saveState() {
  try { localStorage.setItem(STORE_KEY, JSON.stringify(state)); } catch (e) { toast('Не удалось сохранить данные', false); }
}

